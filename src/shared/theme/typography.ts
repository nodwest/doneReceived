/**
 * Межбуквенный интервал для Inter по его «динамическим метрикам»
 * (rsms.me/inter/dynmetrics): крупный текст плотнее, мелкий почти без
 * изменений. Особенно заметно на кириллице — строки становятся аккуратнее.
 * 28 → -0.59, 22 → -0.4, 15 → -0.13, 13 → -0.04.
 */
export const tracking = (fontSize: number) =>
  Math.round(
    (-0.0223 + 0.185 * Math.exp(-0.1745 * fontSize)) * fontSize * 100,
  ) / 100;
